/** 生成 SVG 字符串 */
function glyphSVG(entry, eraKey, opts = {}) {
  const size = opts.size || 100;
  const color = opts.color || "#e2c88e";
  const def = entry[eraKey];

  // 系统字体（隶书 / 楷书）
  if (def && def.char) {
    // 属性用单引号包裹，内部双引号用于字体名（避免引号冲突破坏 XML）
    const fam = JSON.stringify(def.font);
    return `<svg viewBox="0 0 100 100" width="${size}" height="${size}" xmlns="http://www.w3.org/2000/svg">
      <text x="50" y="50" text-anchor="middle" dominant-baseline="central"
        font-size="86" font-family='${fam}' fill="${color}">${def.char}</text>
    </svg>`;
  }

  const strokes = def || [];
  const vb = (strokes[0] && strokes[0].vb) || 100;
  const baseW = STROKE_W[eraKey] || 3.2;
  const paths = strokes.map(s => {
    const w = s.w || baseW;
    // solid = 真实字形轮廓：纯填充、不描边（描边会让细笔画糊成一团）
    if (s.m === "solid") {
      return `<path d="${s.d}" fill="${color}" fill-rule="nonzero"/>`;
    }
    if (s.m === "fill") {
      return `<path d="${s.d}" fill="${color}" stroke="${color}" stroke-width="${w * 0.6}" stroke-linejoin="round"/>`;
    }
    return `<path d="${s.d}" fill="none" stroke="${color}" stroke-width="${w}"
      stroke-linecap="round" stroke-linejoin="round"/>`;
  }).join("");

  return `<svg viewBox="0 0 ${vb} ${vb}" width="${size}" height="${size}" xmlns="http://www.w3.org/2000/svg">
    ${paths}
  </svg>`;
}

/** 构建 Path2D 列表，供 canvas 使用 */
function glyphPaths(entry, eraKey) {
  const def = entry[eraKey];
  if (!def) return { paths: [], text: null, vb: 100 };
  if (def.char) return { paths: [], text: def, vb: 100 };
  const vb = (def[0] && def[0].vb) || 100;
  return {
    vb,
    paths: def.map(s => ({ p: new Path2D(s.d), w: s.w || STROKE_W[eraKey] || 3.2, m: s.m || "stroke" })),
    text: null
  };
}

